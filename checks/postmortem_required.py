#!/usr/bin/env python3
"""Разбирали инцидент — зафиксируй разбор.

Почему скриптом, а не регекспом: одного упоминания слова «упало» мало, чтобы
объявить сессию разбором инцидента, а ложное срабатывание на `Stop` — это
заблокированное закрытие сессии, то есть самый раздражающий вид ошибки.
Поэтому решение принимается по совокупности сигналов, а не по одному слову.

Вход  (stdin):  {"event": <событие хука>, "sources": {...}}
Выход (stdout): {"violated": bool, "reason": "<одна строка>"}
"""

import json
import re
import sys

# Сильный сигнал: одного достаточно. Это слова, которые в рабочей переписке
# почти не встречаются вне разбора реального сбоя.
STRONG = [
    r"\bпостмортем\w*\b",
    # \bpostmortem\b (латиницей) убран: попадается в англоязычных цитатах из
    # ревью и документации, а не в просьбе написать разбор.
    # Голое слово «инцидент» в сильные не годится: в речи оно чаще всего ссылка
    # на прошлый разбор («тз-aware даёт ошибку (инцидент BSGD-4382)»). Сильный
    # сигнал — конструкция про происходящее сейчас.
    r"\b(?:разбира\w+|разбор|разберём|разберем)\s+\S*\s*инцидент",
    r"\bинцидент\s+(?:вчера|сегодня|ночью|утром|на\s+проде|в\s+проде)\b",
    r"\b(?:был|была|случился|случилась|произош[её]л|прилетел)\s+инцидент\b",
    r"\bу\s+нас\s+инцидент\b",
    r"\bпрод(?:акшен)?\s+(?:лежал|упал|лёг|лег)\b",
    r"\bупало\s+в\s+проде\b",
    r"\bна\s+проде\s+(?:упал|сломал|лежал|не\s+работа)",
    # P1/P2 убраны намеренно: в речи это почти всегда приоритет тикета
    # («накидали задач P1»), а не severity инцидента.
    r"\bденьги\s+(?:ушли|улетели)\s+не\s+(?:туда|тем)\b",
    # прямой маркер разбора: так говорят про сбой, а не про обычную отладку
    r"\bразбира\w+,?\s+(?:что\s+)?(?:случилось|произошло)\b",
    r"\bчто\s+(?:там\s+)?(?:случилось|произошло)\s+(?:вчера|ночью|в\s+проде)\b",
    # «авари\w+» целиком не годится: в QB «аварийная панель» и «форма аварийного
    # вывода» — названия элементов интерфейса. Ловим только событие, не термин.
    r"\bавария\s+(?:на\s+проде|вчера|сегодня|ночью)\b",
    r"\b(?:была|случилась|произошла)\s+авария\b",
    r"\bпрод(?:акшен)?\s+лежи[тл]\b",
    r"\bбаг\s+(?:дош[её]л|доехал|уехал)\s+до\s+прода\b",
    r"\bсроч\w+\s+(?:чини|фикси|катим|откат)\w*\b",
    r"\bоткатили\s+(?:релиз|деплой|на\s+прод)\w*\b",
    r"\b(?:модуль|сервис|шлюз|коллектор|бот)\s+\w*\s*(?:молчал|не\s+создавал|не\s+отвеча)\w*\b",
]

# Слабые слова оставлены только для пояснения в reason. Решение по ним НЕ
# принимается: в многочасовой сессии на 10 МБ пара слов вроде «сломал» и «упал»
# набирается всегда — на реальных данных это давало срабатывание на каждой
# третьей обычной отладке. Инцидент опознаётся конструкцией, а не словарём.
CONTEXT = [
    r"\bсломал\w*\b",
    r"\bупал\w*\b",
    r"\bне\s+работа(?:ет|л|ло)\b",
    r"\bошибка\s+в\s+проде\b",
    r"\bкритич\w*\b",
    r"\bпотер\w+\s+(?:данн|заяв|ордер)\w*",
    r"\bдубл(?:ь|и|ирован)\w*\s+(?:ордер|платеж|транзакц)\w*",
    r"\bregression\b|\bрегресс\w*\b",
    # «янус лёг», «проц падал» — самые ходовые формулировки про сбой сервиса,
    # но по отдельности слишком общие, поэтому слабые
    r"\b(?:лёг|лег|легла|слёг)\b",
    r"\bпада(?:л|ла|ло|ет|ют)\b",
    r"\bумер(?:ла|ло)?\b",
    r"\bзавис(?:ал|ла|ло|ает)\w*\b",
    r"\bинцидент\w*\b",
]

# Разбор зафиксирован. Skill(postmortem) есть только в QB; вне его фиксацией
# считается ЗАПИСЬ заметки в incidents/ — требовать конкретный скилл глобально
# нельзя, в личных проектах его просто нет.
#
# Важно: именно вызов записи, а не упоминание пути. Проверка на голое
# `incidents/` давала 16 ложных «зафиксировано» из 25 реальных сессий — путь
# постоянно попадается в списке related чужой заметки и в выдаче поиска.
FIXED = [
    r"Skill\(postmortem\)",
    r"(?:write_note|patch_note|create_note|append_to_note|\bWrite\b)[^\n]{0,400}?(?:incidents?|postmortems?)/",
]

# Сессия про сам движок гейтов: слова-сигналы в ней означают обсуждение правил,
# а не сбой. Без этого исключения движок начинает срабатывать на разработке
# самого себя, что читается как ложное срабатывание и подрывает доверие.
META = [
    r"q0t-gates",
    r"postmortem_required\.py",
    r"\bправил[оа]\s+`?postmortem",
]


def hits(text: str, patterns: list[str]) -> list[str]:
    return [p for p in patterns if re.search(p, text, re.IGNORECASE)]


def main() -> None:
    try:
        payload = json.load(sys.stdin)
    except Exception as e:  # noqa: BLE001 — движок трактует падение как «не сработало»
        print(json.dumps({"violated": False, "reason": f"не разобрал вход: {e}"}))
        return

    sources = payload.get("sources", {})
    # Сигнал ищем ТОЛЬКО в речи человека: полный транскрипт содержит тексты
    # загруженных скиллов, прочитанные заметки и выдачу поиска, где слово
    # «инцидент» встречается почти всегда.
    said = sources.get("transcript.user", "")
    transcript = sources.get("transcript", "")
    tools = sources.get("transcript.tools", "")

    if not said:
        print(json.dumps({"violated": False, "reason": "нет реплик человека"}))
        return

    if hits(said, META):
        print(json.dumps({"violated": False, "reason": "сессия про сам движок правил"}))
        return

    strong = hits(said, STRONG)
    if not strong:
        print(json.dumps({"violated": False, "reason": "признаков инцидента нет"}))
        return

    haystack = transcript + "\n" + tools
    if hits(haystack, FIXED):
        print(json.dumps({"violated": False, "reason": "разбор зафиксирован"}))
        return

    signal = strong[0]
    print(json.dumps({
        "violated": True,
        "reason": f"признак инцидента ({signal}), записи разбора нет",
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
